-- Delivery Panel rebuild migration.
-- Run once in Supabase SQL Editor.

ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS delivery_otp TEXT,
  ADD COLUMN IF NOT EXISTS delivery_otp_attempts INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS delivery_otp_locked_until TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS delivery_otp_verified_at TIMESTAMPTZ;

UPDATE public.orders
SET delivery_otp = LPAD((floor(random() * 10000))::INT::TEXT, 4, '0')
WHERE delivery_otp IS NULL;

CREATE TABLE IF NOT EXISTS public.delivery_earnings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES public.orders(id) ON DELETE CASCADE,
  partner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (fee >= 0),
  tip NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (tip >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.delivery_earnings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Delivery partners read own earnings" ON public.delivery_earnings;
CREATE POLICY "Delivery partners read own earnings"
  ON public.delivery_earnings FOR SELECT TO authenticated
  USING (partner_id = auth.uid());

DROP POLICY IF EXISTS "Delivery partners read assigned orders" ON public.orders;
CREATE POLICY "Delivery partners read assigned orders"
  ON public.orders FOR SELECT TO authenticated
  USING (delivery_boy_id::text = auth.uid()::text);

CREATE INDEX IF NOT EXISTS idx_delivery_earnings_partner_created
  ON public.delivery_earnings(partner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_delivery_otp_lock
  ON public.orders(delivery_boy_id, delivery_otp_locked_until);

CREATE OR REPLACE FUNCTION public.purge_old_delivery_locations()
RETURNS VOID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE public.users
  SET current_lat = NULL, current_lng = NULL, location_updated_at = NULL
  WHERE location_updated_at < now() - INTERVAL '24 hours';
$$;

REVOKE ALL ON FUNCTION public.purge_old_delivery_locations() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.purge_old_delivery_locations() TO service_role;
